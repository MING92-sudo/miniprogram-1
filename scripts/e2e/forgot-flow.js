const automator = require('miniprogram-automator'); const path = require('path')
const sleep = ms => new Promise(r => setTimeout(r, ms))
;(async () => {
  const mp = await automator.connect({ wsEndpoint: 'ws://localhost:9421', timeout: 60000 }); await sleep(1500)
  await mp.evaluate(() => wx.clearStorageSync())
  await mp.reLaunch('/pages/login/forgot'); await sleep(2500)
  const page = await mp.currentPage()
  await page.setData({ newPassword: 'NewPass123', confirmPassword: 'NewPass123' })
  await sleep(300)
  await page.callMethod('onSubmit')
  await sleep(900)
  await mp.screenshot({ path: path.join(__dirname, 'shots', 'forgot-success.png') })
  console.log('shot forgot-success')
  const stored = await mp.evaluate(() => wx.getStorageSync('em_reset_account'))
  console.log('reset account stored:', JSON.stringify(stored))
  await mp.disconnect()
})().catch(e => { console.error('ERR', e.message); process.exit(1) })