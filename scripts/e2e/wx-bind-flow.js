// 微信绑定客户端接线闭环（mock）：登录→我的→绑定→退出→登录页微信一键登录。
const automator = require('miniprogram-automator'); const path = require('path')
const sleep = ms => new Promise(r => setTimeout(r, ms))
;(async () => {
  const mp = await automator.connect({ wsEndpoint: 'ws://localhost:9421', timeout: 60000 }); await sleep(2000)
  await mp.evaluate(() => wx.clearStorageSync())
  await mp.reLaunch('/pages/login/index'); await sleep(2200)
  let page = await mp.currentPage()
  await page.setData({ phone: '13800000001', password: '123456', agreed: true })
  await page.callMethod('onSubmit'); await sleep(2500)
  console.log('after login:', (await mp.currentPage()).path)
  await mp.reLaunch('/pages/profile/index'); await sleep(2200)
  page = await mp.currentPage()
  await page.callMethod('onBindWechat'); await sleep(1500)
  console.log('bound flag:', await mp.evaluate(() => wx.getStorageSync('em_wechat_bound')))
  await mp.screenshot({ path: path.join(__dirname, 'shots', 'wx-bound-profile.png') })
  await page.callMethod('onLogout'); await sleep(2500)
  console.log('after logout:', (await mp.currentPage()).path)
  await mp.screenshot({ path: path.join(__dirname, 'shots', 'wx-login-button.png') })
  page = await mp.currentPage()
  await page.setData({ agreed: true })
  await page.callMethod('onWechatLogin'); await sleep(2500)
  console.log('after wx-login:', (await mp.currentPage()).path)
  await mp.screenshot({ path: path.join(__dirname, 'shots', 'wx-login-home.png') })
  await mp.disconnect()
})().catch(e => { console.error('ERR', e.message); process.exit(1) })